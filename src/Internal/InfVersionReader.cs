using System;
using System.Globalization;
using System.Runtime.InteropServices;

using Windows.Win32;

namespace Nefarius.Utilities.DeviceManagement.Internal;

/// <summary>
///     Reads identity fields from the <c>[Version]</c> section of an INF file via SetupAPI.
/// </summary>
internal static class InfVersionReader
{
    [DllImport("setupapi.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    private static extern unsafe void* SetupOpenInfFileW(char* fileName, string? infClass, uint infStyle,
        uint* errorLine);

    [DllImport("setupapi.dll", SetLastError = true)]
    private static extern unsafe bool SetupCloseInfFile(void* infHandle);

    // SetupGetLineTextW is only generated by CsWin32 when targeting a specific CPU architecture (INFCONTEXT
    // packing), so it is declared manually here, like the other hand-written SetupAPI imports of this library.
    [DllImport("setupapi.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    private static extern unsafe bool SetupGetLineTextW(void* context, void* infHandle, string section, string key,
        char* returnBuffer, uint returnBufferSize, uint* requiredSize);

    internal sealed class InfIdentity
    {
        public string? Provider { get; init; }
        public string? ClassName { get; init; }
        public Guid ClassGuid { get; init; }
        public Version? DriverVersion { get; init; }
        public DateTime? DriverDate { get; init; }
    }

    /// <summary>
    ///     Opens the INF and reads Provider, DriverVer and class information. Returns null if the INF cannot be opened.
    /// </summary>
    public static unsafe InfIdentity? Read(string infPath)
    {
        void* handle;

        fixed (char* path = infPath)
        {
            handle = SetupOpenInfFileW(path, null, 2 /* INF_STYLE_WIN4 */, null);
        }

        // INVALID_HANDLE_VALUE
        if (handle == (void*)-1 || handle == null)
        {
            return null;
        }

        try
        {
            string? provider = ReadField(handle, "Provider");
            string? driverVer = ReadField(handle, "DriverVer");
            string? classGuidText = ReadField(handle, "ClassGUID");
            string? className = ReadField(handle, "Class");

            Guid classGuid = Guid.Empty;
            if (!string.IsNullOrEmpty(classGuidText) && Guid.TryParse(classGuidText, out Guid parsed))
            {
                classGuid = parsed;
                className = ClassNameFromGuid(parsed) ?? className;
            }

            ParseDriverVer(driverVer, out DateTime? date, out Version? version);

            return new InfIdentity
            {
                Provider = provider,
                ClassName = string.IsNullOrEmpty(className) ? null : className,
                ClassGuid = classGuid,
                DriverVersion = version,
                DriverDate = date
            };
        }
        finally
        {
            SetupCloseInfFile(handle);
        }
    }

    /// <summary>
    ///     Parses an INF <c>DriverVer</c> value of the form <c>MM/DD/YYYY[,a.b.c.d]</c>.
    /// </summary>
    internal static void ParseDriverVer(string? value, out DateTime? date, out Version? version)
    {
        date = null;
        version = null;

        if (string.IsNullOrWhiteSpace(value))
        {
            return;
        }

        string[] parts = value!.Split(',');

        if (DateTime.TryParseExact(parts[0].Trim(), new[] { "M/d/yyyy", "MM/dd/yyyy" },
                CultureInfo.InvariantCulture, DateTimeStyles.None, out DateTime parsedDate))
        {
            date = parsedDate;
        }

        if (parts.Length > 1 && Version.TryParse(parts[1].Trim(), out Version? parsedVersion))
        {
            version = parsedVersion;
        }
    }

    /// <summary>
    ///     Derives the original INF name from a staged store path such as
    ///     <c>C:\Windows\System32\DriverStore\FileRepository\foo.inf_amd64_0123abcd\foo.inf</c>.
    /// </summary>
    internal static string? GetOriginalInfName(string storeInfPath)
    {
        string trimmed = storeInfPath.TrimEnd('\\');
        int lastSeparator = trimmed.LastIndexOf('\\');

        if (lastSeparator < 0)
        {
            return null;
        }

        string dirName;
        string last = trimmed.Substring(lastSeparator + 1);

        if (last.EndsWith(".inf", StringComparison.OrdinalIgnoreCase))
        {
            string parent = trimmed.Substring(0, lastSeparator);
            int parentSeparator = parent.LastIndexOf('\\');

            if (parentSeparator < 0)
            {
                return null;
            }

            dirName = parent.Substring(parentSeparator + 1);
        }
        else
        {
            dirName = last;
        }

        // The original name is the prefix up to the last ".inf_" separator.
        int index = dirName.LastIndexOf(".inf_", StringComparison.OrdinalIgnoreCase);

        // Needs a non-empty prefix and at least one character after the separator.
        if (index <= 0 || index + 5 >= dirName.Length)
        {
            return null;
        }

        return dirName.Substring(0, index + 4);
    }

    private static unsafe string? ReadField(void* handle, string key)
    {
        uint required = 0;

        // Query the required size first; a missing key makes this fail.
        SetupGetLineTextW(null, handle, "Version", key, null, 0, &required);

        if (required == 0)
        {
            return null;
        }

        char[] buffer = new char[required];

        fixed (char* p = buffer)
        {
            if (!SetupGetLineTextW(null, handle, "Version", key, p, required, &required))
            {
                return null;
            }
        }

        string value = new string(buffer).TrimEnd('\0').Trim();
        return value.Length == 0 ? null : value;
    }

    private static unsafe string? ClassNameFromGuid(Guid classGuid)
    {
        char[] buffer = new char[256];

        fixed (char* p = buffer)
        {
            if (!PInvoke.SetupDiClassNameFromGuid(&classGuid, p, (uint)buffer.Length, null))
            {
                return null;
            }
        }

        string name = new string(buffer).TrimEnd('\0');
        return name.Length == 0 ? null : name;
    }
}